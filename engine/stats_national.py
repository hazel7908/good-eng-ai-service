def _plan(path, sec):
    """시트를 한 번 읽고 좌표를 푼다 — 시군마다 다시 읽지 않기 위해서."""
    spec = SOURCES[sec]
    rows, sheet = sheet_rows(path, spec["시트"])
    # ⚠️ 자동 인식은 **데이터가 거의 다 글자인 표**에서 실패한다 — 상수원보호구역은
    #    보호구역명·시도·시군·날짜·소재지가 전부 텍스트라 머리글과 안 갈린다.
    #    그런 표는 `머리글행` 으로 못 박는다.
    #      정수 n  → 1~n 행이 머리글
    #      [a, b]  → **그 행들만**. 위쪽에 요약 블록이 낀 표에 필요하다 —
    #                산림유전자원은 2행에 `면적/총면적` 요약이 있어 1~7 로 잡으면
    #                `총면적` 이 엉뚱한 열(관리번호)에 붙는다
    hr = spec.get("머리글행")
    band = (list(range(hr)) if isinstance(hr, int)
            else [r - 1 for r in hr] if hr else header_band(rows))
    cols = header_cols(rows, band)
    def col(v, required=True):
        """정규식 또는 **열 번호**. 이름으로 못 가르는 자리가 있다 —
        상수원보호구역의 `행정구역` 은 시도·시군 두 열이 병합돼 **이름이 같다**."""
        if isinstance(v, int):
            return v
        return find_col(cols, v, required=required)

    return spec, rows, sheet, band, {
        "지자체": col(spec["지자체열"]),
        "제외": col(spec["제외열"], required=False),
        "영행제외": col(spec["영행제외열"], required=False)
        if "영행제외열" in spec else None,
        "열": {label: col(pat, required=False) for label, pat in spec["열"].items()},
    }


def _rows_to_records(rows, picked, zero_c):
    out = []
    for row in rows:
        if zero_c is not None and len(row) > zero_c and num(row[zero_c]) == 0:
            continue                      # 개소수 0 — 이 시군의 시설이 아니다
        out.append({
            label: (CHECK if (c is None or len(row) <= c or row[c] is None
                              or str(row[c]).strip() == "") else row[c])
            for label, c in picked.items()
        })
    return out


def extract(path, sec, region):
    """원자료에서 한 시군의 표를 뽑는다. 반환 (표, 시트명, 원자료에 없는 열)."""
    spec, rows, sheet, band, at = _plan(path, sec)
    hit = region_rows(rows, band[-1] + 1, at["지자체"], region, skip_col=at["제외"])
    return (_rows_to_records(hit, at["열"], at["영행제외"]), sheet,
            [k for k, v in at["열"].items() if v is None])


