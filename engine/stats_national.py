def self_test():
    ok = bad = 0
    for label, path, sec, region, (name_h, cap_h, val_h), expect in GOLDEN:
        if not path.exists():
            print(f"⏭  {label}: 원자료 없음 {path.name}")
            continue
        table, sheet, missing = extract(path, sec, region)
        if expect is None:
            # 판이 골든셋과 달라 행 수를 못 맞춘다 — **뽑히는지만** 본다
            print(f"\n{'✅' if table else '❌'} {label} · {region} — {len(table)}행 (판 상이, 존재만 확인)")
            ok, bad = (ok + 1, bad) if table else (ok, bad + 1)
            continue
        head = f"{label} · {region} — {len(table)}행 (기대 {len(expect)})"
        if len(table) != len(expect):
            print(f"\n❌ {head}"); bad += 1
        else:
            print(f"\n✅ {head}")
        if missing:
            print(f"   ⚠️ 원자료에 없는 열: {', '.join(missing)}")
        for got, exp in zip(table, expect):
            for what, g, e in zip((name_h, cap_h, val_h),
                                  (got[name_h], got[cap_h], got[val_h]), exp):
                gn, en = num(g), num(e)
                hit = (abs(gn - en) < 0.05) if (gn is not None and en is not None) \
                    else (str(g) == str(e))
                ok, bad = (ok + 1, bad) if hit else (ok, bad + 1)
                if not hit:
                    print(f"   ❌ {what}: {g!r}  ≠ 기대 {e!r}")
    print(f"\n=== 자체검증: {ok} OK · {bad} 불일치 ===")
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("excel", nargs="?")
    ap.add_argument("--sec", choices=list(SOURCES))
    ap.add_argument("--region")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    if not (a.excel and a.sec and a.region):
        ap.error("excel · --sec · --region 이 모두 필요하다 (또는 --self-test)")
    table, sheet, missing = extract(a.excel, a.sec, a.region)
    render(table, a.sec, a.region, sheet, missing)
    return 0


