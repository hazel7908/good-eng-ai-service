def gun_key(value):
    """지자체 열 값 → **정규화한 시군 키**. 자료마다 생김새가 다르다.

        상수도  `강원특별자치도 원주시` → 시도명이 앞에 붙는다
        하수도  `괴산군`                → 시군만 온다
        산림청  `원주` / `원주시`        → ⚠️ **같은 파일 안에서 섞여 있다**

    마지막이 결정적이다 — 접미(`시`·`군`·`구`)를 떼지 않으면 **같은 시군이 두 키로 갈려**
    행이 조용히 빠진다 (원주 산림유전자원 2행 중 1행이 사라졌다).
    시도 집계 행(`강원특별자치도 군` · `서울특별시`)은 `None` 을 돌려 걸러낸다.
    """
    if not value:
        return None
    v = str(value).strip()
    if " " in v:
        v = v.rsplit(" ", 1)[-1]
    if not v or v in ("시", "군", "구") or v in SIDO:
        return None
    return re.sub(r"[시군구]$", "", v) or None


def extract_all(path, sec):
    """**전국을 한 번에** 뽑는다 — 시트를 시군마다 다시 읽지 않는다.

    반환 (`{시군: [행…]}`, 시트명, 원자료에 없는 열).

    ⚠️ 지자체 열은 **끌어 내려야 한다** (2021 하수도판은 병합이라 아래 행이 `None`).
    그러면 시도 집계 행에 앞 시군이 끌려오는데, 그 행들은 `제외열` 이 `합계`·`소계` 라
    걸러진다 — **끌어채우기와 집계행 제외가 짝이다.** 하나만 하면 조용히 틀린다.
    """
    spec, rows, sheet, band, at = _plan(path, sec)
    reg_c, skip_c = at["지자체"], at["제외"]
    buckets, last = {}, None
    for row in rows[band[-1] + 1:]:
        if len(row) <= reg_c:
            continue
        if row[reg_c] is not None and str(row[reg_c]).strip():
            last = str(row[reg_c]).strip()
        if skip_c is not None and len(row) > skip_c:
            sv = row[skip_c]
            if sv is None or str(sv).strip() in ("계", "소계", "합계"):
                continue
        gun = gun_key(last)
        if gun:
            buckets.setdefault(gun, []).append(row)
    return ({g: _rows_to_records(rs, at["열"], at["영행제외"])
             for g, rs in buckets.items()},
            sheet, [k for k, v in at["열"].items() if v is None])


def render(table, sec, region, sheet=None, missing=None):
    print(f"\n## {sec} — {region}  ({len(table)}행)" + (f"  ← 시트 `{sheet}`" if sheet else ""))
    if missing:
        print(f"   ⚠️ 원자료에 없는 열: {', '.join(missing)} → {CHECK}")
    if not table:
        print(f"   {CHECK} — 해당 시군의 행이 없다 (0개소일 수도, 지자체명 표기가 다를 수도)")
        return
    heads = list(table[0])
    print("   " + " | ".join(heads))
    for r in table:
        print("   " + " | ".join(
            f"{r[h]:,}" if isinstance(r[h], (int, float)) else str(r[h]) for h in heads))


